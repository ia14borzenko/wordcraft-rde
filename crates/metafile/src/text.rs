//! WMF text bytes as Unicode. A WMF text record stores 8-bit characters, and the charset of the font
//! selected into the playback DC names their code page (MS-WMF 2.3.3.5, "META_EXTTEXTOUT Record"):
//! ANSI is Windows-1252, RUSSIAN Windows-1251, EASTEUROPE Windows-1250, and a symbol font (Symbol,
//! whose characters are the Adobe Symbol encoding) maps to the standard Unicode characters. EMF text
//! is UTF-16 and never comes here.
//!
//! The symbol correspondence is the published Adobe Symbol encoding table
//! (<https://www.unicode.org/Public/MAPPINGS/VENDORS/ADOBE/symbol.txt>), the same one
//! `wordcraft_doc::symbol_fonts` keeps for document text; the metafile reader sits below the document
//! model (L1, no workspace dependencies), so it carries its own copy. Unlike the document model's copy
//! this one also maps the table's corporate-use codes 0xE6–0xFE — the bracket, parenthesis, brace and
//! integral pieces MathType builds tall delimiters from — to the Unicode Symbol Pieces block
//! (U+239B–U+23AE), the characters that stand for exactly those pieces.

/// SYMBOL charset: the Adobe Symbol encoding.
const SYMBOL_CHARSET: u8 = 2;
/// RUSSIAN charset: Windows-1251.
const RUSSIAN_CHARSET: u8 = 204;
/// EASTEUROPE charset: Windows-1250.
const EASTEUROPE_CHARSET: u8 = 238;

/// The Unicode text of a WMF record's bytes, decoded by the selected font's `charset` and `face`.
/// Trailing NULs (some writers count the terminator) are dropped.
pub(crate) fn decode(bytes: &[u8], charset: u8, face: &[u16; 32]) -> String {
    let name = String::from_utf16_lossy(face);
    let name = name.trim_end_matches('\0').trim();
    let text: String = if charset == SYMBOL_CHARSET || is_symbol_face(name) {
        bytes.iter().map(|b| symbol(*b)).collect()
    } else {
        bytes.iter().map(|b| mt_extra(*b).unwrap_or_else(|| codepage(*b, charset))).collect()
    };
    text.trim_end_matches('\0').to_string()
}

/// MathType's own fonts have no published encoding table. The only code these previews use is 0x26
/// in MT Extra, the dot-above accent drawn over the letter beside it: LibreOffice renders the same
/// metafiles with a dot there, so it maps to the spacing dot U+02D9. Other codes of that font stay
/// their Windows-1252 character (a documented approximation).
fn mt_extra(b: u8) -> Option<char> {
    (b == 0x26).then_some('\u{02D9}')
}

/// Whether `face` is one of Word's symbol fonts whose bytes are the Adobe Symbol encoding.
fn is_symbol_face(face: &str) -> bool {
    face.eq_ignore_ascii_case("symbol") || face.eq_ignore_ascii_case("symbol (pcl6)")
}

/// One byte of a single-byte Windows code page as a character. ANSI (0), DEFAULT (1) and charsets this
/// reader does not know (Greek, Turkish, Hebrew, Arabic, Baltic, Vietnamese, OEM…) are read as
/// Windows-1252: Latin text stays right, other scripts show their Latin letters (a documented
/// limitation; the charsets listed above have their own table).
fn codepage(b: u8, charset: u8) -> char {
    match charset {
        RUSSIAN_CHARSET => table_char(&CP1251, b),
        EASTEUROPE_CHARSET => table_char(&CP1250, b),
        _ => {
            if (0x80..0xA0).contains(&b) {
                CP1252.get(usize::from(b) - 0x80).map_or_else(|| char_of(u16::from(b)), |u| char_of(*u))
            } else {
                // ASCII and Latin-1 agree with Windows-1252 outside 0x80..=0x9F.
                char_of(u16::from(b))
            }
        }
    }
}

/// A high byte of a 128-entry Windows code page table.
fn table_char(table: &[u16; 128], b: u8) -> char {
    if b < 0x80 {
        return char_of(u16::from(b));
    }
    table.get(usize::from(b) - 0x80).map_or_else(|| char_of(u16::from(b)), |u| char_of(*u))
}

/// One byte of the Adobe Symbol encoding as a character; a code with no Unicode equivalent stays its
/// own low character, so nothing silently vanishes.
fn symbol(b: u8) -> char {
    let code = usize::from(b);
    let Some(u) = code.checked_sub(0x20).and_then(|i| SYMBOL.get(i)).copied().filter(|u| *u != 0) else {
        return char_of(u16::from(b));
    };
    char::from_u32(u).unwrap_or_else(|| char_of(u16::from(b)))
}

/// A code point as a character; an unpaired one (the tables' U+FFFD placeholders are fine) becomes
/// the replacement character.
fn char_of(code: u16) -> char {
    char::from_u32(u32::from(code)).unwrap_or(char::REPLACEMENT_CHARACTER)
}

